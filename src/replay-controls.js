(function (root) {
  const presets = [
    ['暂停 / 继续','F6','demo_togglepause'], ['播放面板','F7','demoui'],
    ['半速播放','F8','demo_timescale 0.5'], ['正常速度','F9','demo_timescale 1'],
    ['两倍速度','F10','demo_timescale 2'], ['四倍速度','','demo_timescale 4'],
    ['切换透视','F11','toggle spec_show_xray 0 1'],
    ['上一个玩家','','spec_prev'], ['下一个玩家','','spec_next'],
    ['切换观察视角','','spec_mode']
  ];
  const keys = ['', ...Array.from({length:12},(_,i)=>`F${i+1}`), ...'ABCDEFGHIJKLMNOPQRSTUVWXYZ', ...'0123456789', 'SPACE','TAB','ENTER','BACKSPACE','UPARROW','DOWNARROW','LEFTARROW','RIGHTARROW','HOME','END','PGUP','PGDN','INS','DEL','MOUSE1','MOUSE2','MOUSE3','MOUSE4','MOUSE5','MWHEELUP','MWHEELDOWN'];
  const defaults = () => ({enabled:true, bindings:presets.map(([label,key,command])=>({label,key,command}))});
  function keyFromEvent(event) {
    if (event.ctrlKey || event.altKey || event.metaKey || event.shiftKey) return '';
    const code = event.code || '';
    if (/^Key[A-Z]$/.test(code)) return code.slice(3);
    if (/^Digit[0-9]$/.test(code)) return code.slice(5);
    if (/^F([1-9]|1[0-2])$/.test(code)) return code;
    return {Space:'SPACE',Tab:'TAB',Enter:'ENTER',Backspace:'BACKSPACE',ArrowUp:'UPARROW',ArrowDown:'DOWNARROW',ArrowLeft:'LEFTARROW',ArrowRight:'RIGHTARROW',Home:'HOME',End:'END',PageUp:'PGUP',PageDown:'PGDN',Insert:'INS',Delete:'DEL'}[code] || '';
  }
  function normalize(value = defaults()) {
    if (!value || typeof value.enabled !== 'boolean' || !Array.isArray(value.bindings) || value.bindings.length > 40) throw new Error('回放按键配置无效（最多 40 项）。');
    const used = new Set();
    const bindings = value.bindings.map((row,i) => {
      if (!row || typeof row.key !== 'string' || typeof row.command !== 'string') throw new Error(`第 ${i+1} 项配置无效。`);
      const key = row.key.toUpperCase(), command = row.command.trim();
      if (!keys.includes(key)) throw new Error(`第 ${i+1} 项按键不支持。`);
      if (key && used.has(key)) throw new Error(`按键 ${key} 重复，请为每个操作选择不同按键。`);
      if (key) used.add(key);
      const simple = /^(demo_togglepause|demo_pause|demo_resume|demoui|spec_prev|spec_next|spec_mode)$/;
      const speed = /^demo_timescale (0\.25|0\.5|1|2|4|8)$/;
      if (!simple.test(command) && !speed.test(command) && command !== 'toggle spec_show_xray 0 1') throw new Error(`第 ${i+1} 项不是支持的回放指令，请从常用指令中选择。`);
      return {label:String(row.label || `操作 ${i+1}`).replace(/[\r\n]/g,' ').slice(0,40),key,command};
    });
    return {enabled:value.enabled,bindings};
  }
  function cfg(value) {
    const config = normalize(value);
    return '// Generated by CS2 Demo Desk. Loaded on replay launch.\n' + (config.enabled ? config.bindings.filter(x=>x.key).map(x=>`bind "${x.key}" "${x.command}"`).join('\n') : '// Replay bindings disabled.') + '\n';
  }
  const api = {presets,keys,defaults,normalize,cfg,keyFromEvent};
  if (typeof module !== 'undefined') module.exports = api; else root.ReplayControls = api;
})(globalThis);
